package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"text/template"

	"github.com/lisama569/schema-wire-sdk-go/schema"
)

// fileKind 区分渲染的文件类型。
type fileSpec struct {
	name    string
	execute func(g *generator, s *schema.Schema) ([]byte, error)
}

type generator struct {
	pkg       string
	tmpl      *template.Template
	goPackage string
}

func newGenerator(goPackage string) *generator {
	g := &generator{goPackage: goPackage}
	g.tmpl = template.Must(template.New("root").Funcs(tmplFuncs).Parse(descriptorTmpl))
	template.Must(g.tmpl.New("message").Parse(messageTmpl))
	return g
}

// renderFiles 返回文件名 -> 已 gofmt 的文件内容。
// 消息文件按消息名排序，保证逐字节确定性。
func (g *generator) renderFiles(s *schema.Schema) (map[string][]byte, error) {
	out := map[string][]byte{}

	var desc bytes.Buffer
	if err := g.tmpl.ExecuteTemplate(&desc, "descriptor", renderCtx{Schema: s, Pkg: g.goPackage}); err != nil {
		return nil, err
	}
	fmtd, err := format.Source(desc.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%w: descriptor template: %v", errInternal, err)
	}
	out["schema_descriptor.go"] = fmtd

	for _, m := range s.Messages {
		var buf bytes.Buffer
		if err := g.tmpl.ExecuteTemplate(&buf, "message", renderCtx{
			Schema: s, Pkg: g.goPackage, Msg: m,
		}); err != nil {
			return nil, err
		}
		fmtd, err := format.Source(buf.Bytes())
		if err != nil {
			return nil, fmt.Errorf("%w: message %s template: %v", errInternal, m.Name, err)
		}
		out[snakeName(m.Name)+".go"] = fmtd
	}
	return out, nil
}

type renderCtx struct {
	Schema *schema.Schema
	Pkg    string
	Msg    *schema.Message
}

// snakeName 把 CamelCase 转为稳定的 snake_case 文件名。
func snakeName(s string) string {
	var b strings.Builder
	for i, r := range s {
		if i > 0 && isUpper(r) {
			b.WriteByte('_')
		}
		b.WriteRune(toLower(r))
	}
	return b.String()
}

func isUpper(r rune) bool { return r >= 'A' && r <= 'Z' }
func toLower(r rune) rune {
	if isUpper(r) {
		return r + ('a' - 'A')
	}
	return r
}

var errInternal = &GenError{Kind: KindInternal}

const descriptorTmpl = `{{define "descriptor"}}
// Code generated by schemagen; DO NOT EDIT.
//
// 本文件由 IDL schema 生成，描述协议版本元信息，
// 运行时据此判断版本兼容性。

package {{.Pkg}}

import (
	"fmt"

	{{printf "%q" "github.com/lisama569/schema-wire-sdk-go/wire"}}
)

// SchemaMaxVersion 是生成此代码时 schema 声明的最新版本。
const SchemaMaxVersion uint32 = {{.Schema.Version}}

// SchemaPolicy 是 schema 声明的兼容策略（"additive" 或 "none"）。
const SchemaPolicy = {{printf "%q" (str .Schema.Policy)}}

// requireReadable 拒绝结构可解析但版本无法读取的数据。
//
// version==0 已在 wire.DecodeEnvelope 阶段判定为不兼容；
// 此处额外拒绝超过本代码已知上限的版本（当调用方选择严格模式时）。
func requireReadable(version, knownVersion uint32, strict bool) error {
	if version == 0 {
		return &wire.Error{Kind: wire.KindIncompatibleVersion,
			Detail: "envelope version is 0"}
	}
	if strict && version > knownVersion {
		return &wire.Error{Kind: wire.KindIncompatibleVersion,
			Detail: fmt.Sprintf("envelope version %d exceeds known version %d (code schema max %d)",
				version, knownVersion, SchemaMaxVersion)}
	}
	return nil
}
{{end}}
`
