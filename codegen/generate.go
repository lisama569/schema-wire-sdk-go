package codegen

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/lisama569/schema-wire-sdk-go/schema"
)

// generatedPrefix 标记受管文件；Generate 只覆盖/创建带该头的文件。
const generatedHeader = "// Code generated by schemagen; DO NOT EDIT."

// Options 控制一次代码生成的产物位置与包名。
type Options struct {
	// Dir 是产物输出目录（生成物直接放入该目录）。
	GoPackage string
}

// Result 是一次成功生成的结果描述。
type Result struct {
	// Files 是写入的文件名（相对 Dir），按确定顺序排列。
	Files []string
}

// Generate 为一个 schema 生成 Go 编解码代码。
//
// 确定性：相同 schema 与包名产出逐字节一致；字段顺序由校验阶段排序固定。
// 原子性：所有文件先写入 Dir 下独占的临时目录，成功后逐个替换进 Dir；
// 任何一步失败都清理临时目录，Dir 中不留下半成品。
// 并发生成不同目标包时使用各自独立的临时目录，互不污染。
func Generate(ctx context.Context, s *schema.Schema, outDir string, opts Options) (*Result, error) {
	if s == nil {
		return nil, &GenError{Kind: KindInvalidSchema, Detail: "nil schema"}
	}
	// 不修改调用方传入的 schema：Validate 会就地排序/建索引，
	// 同一 schema 可能被并发生成多个目标包，先深拷贝再校验。
	s = cloneSchema(s)
	if err := s.Validate(); err != nil {
		return nil, &GenError{Kind: KindInvalidSchema, Detail: err.Error()}
	}
	pkg := opts.GoPackage
	if pkg == "" {
		if s.Package != "" {
			pkg = s.Package
		} else {
			pkg = filepath.Base(filepath.Clean(outDir))
		}
	}
	if !validIdent(pkg) {
		return nil, &GenError{Kind: KindInvalidSchema, Detail: "invalid go package name: " + pkg}
	}

	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return nil, &GenError{Kind: KindIO, Detail: "create output dir: " + err.Error()}
	}

	g := newGenerator(pkg)
	files, err := g.renderFiles(s)
	if err != nil {
		return nil, err
	}

	// 冲突预检：目标路径已存在且不是受管文件时拒绝（不覆盖手写代码）。
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		dst := filepath.Join(outDir, name)
		existing, err := os.ReadFile(dst)
		switch {
		case err == nil:
			if !strings.HasPrefix(string(existing), generatedHeader) {
				return nil, &GenError{Kind: KindConflict,
					Detail: fmt.Sprintf("refuse to overwrite unmanaged file: %s", dst)}
			}
		case os.IsNotExist(err):
			// ok
		default:
			return nil, &GenError{Kind: KindIO, Detail: "inspect " + dst + ": " + err.Error()}
		}
	}

	// 独占临时目录，保证并发互不干扰。
	stage, err := os.MkdirTemp(outDir, ".schemagen-stage-*")
	if err != nil {
		return nil, &GenError{Kind: KindIO, Detail: "create staging dir: " + err.Error()}
	}
	cleanup := func() { _ = os.RemoveAll(stage) }

	for _, name := range names {
		if err := ctx.Err(); err != nil {
			cleanup()
			return nil, &GenError{Kind: KindIO, Detail: "canceled: " + err.Error()}
		}
		if err := os.WriteFile(filepath.Join(stage, name), files[name], 0o644); err != nil {
			cleanup()
			return nil, &GenError{Kind: KindIO, Detail: "write staged " + name + ": " + err.Error()}
		}
	}

	// 暂存内容必须是可编译的 Go 代码（gofmt 在渲染阶段已保证语法正确）。
	for _, name := range names {
		if err := os.Rename(filepath.Join(stage, name), filepath.Join(outDir, name)); err != nil {
			cleanup()
			return nil, &GenError{Kind: KindIO, Detail: "install " + name + ": " + err.Error()}
		}
	}
	cleanup()
	return &Result{Files: names}, nil
}

func validIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') {
			continue
		}
		if i > 0 && r >= '0' && r <= '9' {
			continue
		}
		return false
	}
	return true
}

// cloneSchema 深拷贝 schema，使后续校验/排序不影响调用方对象，
// 从而支持同一 *schema.Schema 被并发生成。
func cloneSchema(in *schema.Schema) *schema.Schema {
	out := &schema.Schema{
		Package:  in.Package,
		Policy:   in.Policy,
		Version:  in.Version,
		Messages: make([]*schema.Message, len(in.Messages)),
	}
	for i, m := range in.Messages {
		nm := &schema.Message{
			Name:   m.Name,
			Fields: make([]*schema.Field, len(m.Fields)),
		}
		for j, f := range m.Fields {
			cp := *f
			nm.Fields[j] = &cp
		}
		out.Messages[i] = nm
	}
	return out
}
